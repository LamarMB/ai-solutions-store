/**
 * Тематический фильтр до OpenAI. Бот — администратор клиники, а не
 * универсальный чат: явный оффтоп и попытки сменить роль отклоняются
 * программно, без запроса к модели. Сомнительное не блокируется — его
 * разбирают модель или правила; тревожные признаки проверяются раньше фильтра.
 */
export const OUT_OF_SCOPE_TEXT =
  "Я ИИ-администратор клиники и могу помочь только с вопросами о здоровье, специалистах, услугах и записи на приём. Чем могу помочь вам?";

export type ScopeContext = {
  clinic: Clinic;
  /** Бот задал вопрос и ждёт ответа («нет», «три дня»). */
  pending: boolean;
  /** Идёт запись или обсуждается жалоба: короткие ответы относятся к ним. */
  inDialog: boolean;
};

export type ScopeVerdict =
  /** Сообщение (или его разрешённая часть) идёт в разговорный сценарий. */
  | { kind: "allowed"; text: string; droppedParts: number }
  | { kind: "rejected"; reason: "offtopic" | "role_change" }
  /** Только приветствие или благодарность — ответ без модели. */
  | { kind: "greeting" }
  | { kind: "thanks" };

