const GREETING_RE =
  /^(?:привет\S*|здравствуй\S*|здрасте|добрый\s+(?:день|вечер)|доброе\s+утро|доброй\s+ночи|доброго\s+(?:дня|времени\s+суток)|хай|hello|hi)[\s!.,)]*$/;
const THANKS_RE =
  /^(?:спасибо|благодарю|спс|thanks|thank\s+you)(?:\s+(?:большое|огромное|вам|тебе))*[\s!.,)]*$/;

const words = (text: string) => text.split(/[^a-zа-я0-9+-]+/).filter(Boolean);

/** Дата или время без других признаков клиники. */
function hasWeakSignal(text: string): boolean {
  const norm = normalizeForRules(text);
  const list = words(norm);
  return (
    WEAK_STEMS.some((stem) => list.some((w) => w.startsWith(stem))) ||
    /(?<!\d)(?:[01]?\d|2[0-3])[:.][0-5]\d(?!\d)/.test(norm)
  );
}

/** Есть ли в фрагменте признаки клиники, записи или здоровья. */
export function hasClinicSignal(text: string, clinic: Clinic): boolean {
  const norm = normalizeForRules(text);
  const list = words(norm);
  if (CLINIC_STEMS.some((stem) => list.some((w) => w.startsWith(stem))))
    return true;
  if (
    CLINIC_WORDS.some((w) =>
      w.includes(" ") ? norm.includes(w) : list.includes(w),
    )
  )
    return true;
  if (
    /сколько\s+(?:\S+\s+)?стоит|режим\s+работы|часы\s+работы|до\s+скольки/.test(
      norm,
    )
  )
    return true;
  const surnames = clinic.doctors.flatMap((d) =>
    d.name
      .toLowerCase()
      .replaceAll("ё", "е")
      .split(" ")
      .filter((p) => p.length > 3)
      .map((p) => p.slice(0, -1)),
  );
  if (surnames.some((stem) => list.some((w) => w.startsWith(stem))))
    return true;
  return (
    detectComplaint(text) !== undefined ||
    detectTrauma(text) !== undefined ||
    detectDuration(text) !== undefined ||
    detectRedFlags(text).length > 0 ||
    isMedicalAdviceRequest(text)
  );
}

export const isRoleChange = (text: string) => {
  const norm = normalizeForRules(text);
  return ROLE_CHANGE.some((re) => re.test(norm));
};

export const isOfftopic = (text: string) => {
  const norm = normalizeForRules(text);
  return OFFTOPIC.some((re) => re.test(norm));
};

/** Разбивает сообщение на части с разделителями: «расскажи анекдот, и ещё болит колено». */
function segments(raw: string): { text: string; sep: string }[] {
  const parts = raw.split(
    /([.!?;\n]+\s*|\s*,\s*(?:(?:и|а|но|кстати)(?:\s+(?:ещ[её]|также))?\s+)?|\s+(?:и|а|но|кстати)(?:\s+(?:ещ[её]|также))?\s+)/i,
  );
  const result: { text: string; sep: string }[] = [];
  for (let i = 0; i < parts.length; i += 2) {
    const text = parts[i] ?? "";
    const sep = parts[i + 1] ?? "";
    if (text.trim() || result.length === 0) result.push({ text, sep });
    else if (result.length > 0) result[result.length - 1].sep += text + sep;
  }
  return result;
}

const SHORT_WORDS = 4;

/**
 * Решение фильтра. Порядок:
 * 1) только приветствие или благодарность — ответ без модели;
 * 2) фрагменты со сменой роли и явным оффтопом отбрасываются, если в них нет
 *    признаков клиники (смена роли отбрасывается всегда);
 * 3) осталась разрешённая часть — она идёт дальше; не осталось ничего,
 *    кроме оффтопа, — отказ без модели;
 * 4) нейтральные фрагменты не блокируются: короткие ответы относятся к
 *    текущему вопросу, остальное разбирают модель или правила.
 */
export function classifyScope(raw: string, ctx: ScopeContext): ScopeVerdict {
  const norm = normalizeForRules(raw);
  if (GREETING_RE.test(norm)) return { kind: "greeting" };
  if (THANKS_RE.test(norm)) return { kind: "thanks" };

  const parts = segments(raw).map((part) => {
    const role = isRoleChange(part.text);
    const off = isOfftopic(part.text);
    // Признаки клиники перевешивают оффтоп («после футбола болит колено»),
    // а дата или время — нет («какая завтра погода»).
    const clinic =
      hasClinicSignal(part.text, ctx.clinic) ||
      (!off && hasWeakSignal(part.text));
    const short = words(normalizeForRules(part.text)).length <= SHORT_WORDS;
    const label: "role" | "off" | "clinic" | "neutral" = role
      ? "role"
      : clinic
        ? "clinic"
        : off
          ? "off"
          : "neutral";
    return { ...part, label, short };
  });
  // Смена роли, разбитая запятыми: «представь, что ты больше не администратор».
  const wholeRole = isRoleChange(raw);
  const blocked = parts.filter((p) => p.label === "role" || p.label === "off");
  if (blocked.length === 0 && !wholeRole)
    return { kind: "allowed", text: raw, droppedParts: 0 };

  // Короткий нейтральный ответ посреди диалога («нет», «сильно») — разрешён.
  const kept = parts.filter(
    (p) =>
      p.label === "clinic" ||
      (p.label === "neutral" && (ctx.pending || ctx.inDialog) && p.short),
  );
  if (
    kept.length > 0 &&
    !(wholeRole && kept.every((p) => p.label !== "clinic"))
  ) {
    const text = parts
      .filter((p) => p.label !== "role" && p.label !== "off")
      .map((p) => p.text + p.sep)
      .join("")
      // Висящая запятая или союз после выброшенной части не нужны.
      .replace(/(?:\s*,|\s+(?:и|а|но|кстати)(?:\s+(?:ещ[её]|также))?)\s*$/i, "")
      .trim();
    return {
      kind: "allowed",
      text,
      droppedParts:
        parts.length -
        parts.filter((p) => p.label !== "role" && p.label !== "off").length,
    };
  }
  return {
    kind: "rejected",
    reason:
      wholeRole || parts.some((p) => p.label === "role")
        ? "role_change"
        : "offtopic",
  };
}
