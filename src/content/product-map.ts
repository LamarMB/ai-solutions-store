/**
 * Интерактивная карта продукта «Демо-Мед» для владельцев клиник: как работает
 * система (схема А), как проходит внедрение (схема Б) и короткая версия для
 * главной. Только реализованное: будущее — отдельным списком с пометкой
 * «В планах» и только в подробной карте. Экраны — вымышленная клиника.
 */

/** Работает в демо; настраивается под клинику; в планах (в коде нет). */
export type MapStatus = "working" | "configurable" | "planned";

export const STATUS_LABELS: Record<MapStatus, string> = {
  working: "Работает в демо",
  configurable: "Настраивается под клинику",
  planned: "В планах",
};

export type MapLane = "patient" | "system" | "staff";

export const LANE_LABELS: Record<MapLane, string> = {
  patient: "Пациент",
  system: "Система",
  staff: "Персонал клиники",
};

type ScreenBase = { id: string; title: string };

/** Снимок экрана демо-стенда (вымышленные данные) в рамке телефона или окна. */
export type ImageScreen = ScreenBase & {
  kind: "phone" | "browser";
  src: string;
  width: number;
  height: number;
  alt: string;
  /** На снимке видны демо-портреты врачей, созданные ИИ. */
  aiPhotos?: boolean;
};

/** Переписка с демо-ботом: реплики сняты с бота и проверяются тестом. */
export type ChatScreen = ScreenBase & {
  kind: "chat";
  lines: readonly ChatLine[];
};

export type DemoScreen = ImageScreen | ChatScreen;

export type MapNode = {
  id: string;
  lane: MapLane;
  /** Колонка на схеме (1–5) — только для широкого экрана. */
  col: number;
  icon: IconName;
  title: string;
  /** Одна строка на карточке узла. */
  summary: string;
  /** Текст для владельца клиники. */
  text: string;
  points: readonly string[];
  /** Что подстраивается под клинику; без поля — работает как есть. */
  setup?: string;
  /** Этапы внедрения, на которых это настраивается. */
  stageIds: readonly string[];
  screenIds: readonly string[];
  /** Связи на схеме: куда ведёт этот шаг. */
  next: readonly string[];
};

export type SetupStage = {
  id: string;
  icon: IconName;
  title: string;
  text: string;
  activities: readonly string[];
  fromClinic: readonly string[];
  outcome: string;
  /** Что это даёт пациенту и клинике — узлы схемы А. */
  nodeIds: readonly string[];
};

export type OverviewStep = {
  id: string;
  icon: IconName;
  title: string;
  text: string;
  nodeIds: readonly string[];
  screenId: string;
};

export type PlannedFeature = { id: string; title: string; text: string };

const chat = (id: keyof typeof demoChats, title: string): ChatScreen => ({
  id: `chat-${id}`,
  kind: "chat",
  title,
  lines: demoChats[id],
});

const phone = (
  id: string,
  title: string,
  alt: string,
  aiPhotos = false,
): ImageScreen => ({
  id,
  kind: "phone",
  title,
  src: `/demo/${id}.webp`,
  width: 540,
  height: 1169,
  alt,
  ...(aiPhotos ? { aiPhotos } : {}),
});

const browser = (
  id: string,
  title: string,
  alt: string,
  aiPhotos = false,
): ImageScreen => ({
  id,
  kind: "browser",
  title,
  src: `/demo/${id}.webp`,
  width: 1200,
  height: 750,
  alt,
  ...(aiPhotos ? { aiPhotos } : {}),
});

