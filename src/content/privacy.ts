/**
 * Политика обработки персональных данных для страницы /privacy и включения
 * приёма заявок (src/requests/store.ts).
 *
 * Сведения об операторе — только из окружения сервера (.env.local), их задаёт
 * владелец; сюда они не выдумываются. Пока не заданы все три — политики нет:
 * /privacy показывает заглушку, формы работают в тестовом режиме. Текст ниже —
 * редакция для формы заявки на сайте; владелец подтверждает её при включении
 * (deploy/requests-enable.sh), юридическая проверка — на стороне владельца.
 */
export type PrivacyPolicy = {
  /** Оператор: ФИО предпринимателя или название организации и ИНН. */
  operator: string;
  /** Email оператора для запросов о персональных данных. */
  contact: string;
  /** Редакция. */
  updatedAt: string;
  sections: readonly { title: string; text: string }[];
};

const INN_RE = /^(\d{10}|\d{12})$/;
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/** Политика из PRIVACY_OPERATOR_NAME, PRIVACY_OPERATOR_INN, PRIVACY_OPERATOR_EMAIL. */
export function privacyPolicyFromEnv(
  env: Record<string, string | undefined>,
): PrivacyPolicy | null {
  const name = env.PRIVACY_OPERATOR_NAME?.trim();
  const inn = env.PRIVACY_OPERATOR_INN?.trim();
  const email = env.PRIVACY_OPERATOR_EMAIL?.trim();
  if (!name || name.length < 3 || !inn || !INN_RE.test(inn)) return null;
  if (!email || !EMAIL_RE.test(email)) return null;
  const operator = `${name}, ИНН ${inn}`;
  return {
    operator,
    contact: email,
    updatedAt: "1 ноября 2026 г.",
    sections: [
      {
        title: "Общие положения",
        text: `Политика определяет, как обрабатываются персональные данные, которые посетители сайта указывают в формах заявки. Оператор персональных данных — ${operator}.`,
      },
      {
        title: "Какие данные обрабатываются",
        text: "Имя, название клиники, выбранный способ связи и контакт (Telegram, телефон или email), а также текст, который вы сами укажете в заявке. Данные пациентов указывать в формах не нужно. IP-адрес не сохраняется: для защиты от спама используется его хэш, который хранится только в памяти сервера и не связывается с заявкой.",
      },
      {
        title: "Цель обработки",
        text: "Связаться с вами по заявке: договориться о демонстрации и ответить на вопросы о продукте. Для рассылок и других целей данные не используются.",
      },
      {
        title: "Основание обработки",
        text: "Ваше согласие, которое вы даёте, отмечая поле согласия в форме заявки (пункт 1 части 1 статьи 6 Федерального закона «О персональных данных» № 152-ФЗ). Без согласия заявка не отправляется.",
      },
      {
        title: "Как обрабатываются данные",
        text: "Заявка не сохраняется на сервере сайта: она передаётся оператору одним сообщением в мессенджер Telegram. Telegram — внешний сервис, его серверы могут находиться за пределами Российской Федерации. Сообщение хранится в переписке оператора до достижения цели обработки или до отзыва согласия, после чего удаляется. Другим лицам данные не передаются.",
      },
      {
        title: "Ваши права",
        text: `Вы можете запросить сведения об обработке ваших данных, потребовать их уточнения или удаления и отозвать согласие, написав оператору на ${email}. Запрос рассматривается в сроки, установленные законом.`,
      },
      {
        title: "Изменение политики",
        text: "Действующая редакция политики публикуется на этой странице.",
      },
    ],
  };
}

export const privacyPolicy = privacyPolicyFromEnv(process.env);
